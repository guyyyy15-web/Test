export function getSpell(spellId) {
  const spell = SPELLS[spellId]
  if (!spell) throw new Error(`Unknown spell: ${spellId}`)
  return spell
}

/** Spells that make sense outside battle (healing, curing, reviving). */
export const FIELD_SPELL_KINDS = new Set(['heal', 'healAll', 'cure', 'revive'])

export function isFieldSpell(spell) {
  return FIELD_SPELL_KINDS.has(spell.kind)
}
