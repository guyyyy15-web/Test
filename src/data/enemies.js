/**
 * The bestiary.
 *
 * Enemies carry flat stats rather than a class and a level curve. They exist
 * for one fight, so there is nothing to gain from deriving their numbers --
 * and a lot to gain from being able to read the whole difficulty curve as a
 * column of `attack` values.
 *
 * `ai` is a weighted list. Entries with `whenHpBelow` only become available
 * once the enemy is hurt, which is enough to make bosses feel like they have
 * phases without any scripting.
 */

function enemy(id, name, tag, color, stats) {
  return {
    id,
    name,
    tag,
    color,
    mp: 0,
    magicAttack: 0,
    magicDefense: 0,
    accuracy: 0,
    evasion: 0,
    critChance: 1,
    attacks: 1,
    traits: [],
    weaknesses: [],
    resistances: [],
    immunities: [],
    statusImmunities: [],
    drops: [],
    ai: [{ weight: 1, kind: 'attack' }],
    ...stats,
  }
}

